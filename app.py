# --- Lightweight content sniffing, used to choose a preview style ----------
HEX_COLOR_RE = re.compile(r"^#(?:[0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")
RGB_COLOR_RE = re.compile(r"^rgba?\(\s*\d{1,3}\s*,\s*\d{1,3}\s*,\s*\d{1,3}\s*(?:,\s*[\d.]+\s*)?\)$", re.IGNORECASE)
HSL_COLOR_RE = re.compile(r"^hsla?\(\s*\d{1,3}\s*,\s*\d{1,3}%\s*,\s*\d{1,3}%\s*(?:,\s*[\d.]+\s*)?\)$", re.IGNORECASE)
URL_RE = re.compile(r"^(https?://|www\.)\S+$", re.IGNORECASE)
TITLE_TAG_RE = re.compile(rb"<title[^>]*>(.*?)</title>", re.IGNORECASE | re.DOTALL)

CODE_HINTS = (
    "def ", "class ", "function", "=>", "import ", "#include", "console.log(",
    "public static", "SELECT ", "</", "{", "};", "print(", "return ",
)


def classify_text(text: str) -> str:
    """Very lightweight heuristic used only to pick a preview style - not exact."""
    stripped = text.strip()
    if HEX_COLOR_RE.match(stripped) or RGB_COLOR_RE.match(stripped) or HSL_COLOR_RE.match(stripped):
        return "color"
    if URL_RE.match(stripped) and " " not in stripped:
        return "url"
    if len(stripped) <= 4000 and (stripped.count("\n") >= 2 or any(hint in text for hint in CODE_HINTS)):
        return "code"
    return "text"


def simulate_cmd_v():
    """Synthesize a system-wide Cmd+V keystroke (macOS only, needs Accessibility access)."""
    if Quartz is None:
        return
    src = Quartz.CGEventSourceCreate(Quartz.kCGEventSourceStateHIDSystemState)
    key_down = Quartz.CGEventCreateKeyboardEvent(src, 9, True)   # 9 == 'V'
    Quartz.CGEventSetFlags(key_down, Quartz.kCGEventFlagMaskCommand)
    key_up = Quartz.CGEventCreateKeyboardEvent(src, 9, False)
    Quartz.CGEventSetFlags(key_up, Quartz.kCGEventFlagMaskCommand)
    Quartz.CGEventPost(Quartz.kCGHIDEventTap, key_down)
    Quartz.CGEventPost(Quartz.kCGHIDEventTap, key_up)


