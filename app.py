    # --- Persistence of pinned items ---------------------------------------

    @staticmethod
    def _make_image_key(image: QImage):
        """Cheap fingerprint used to recognize a previously-seen image."""
        img_bytes = image.bits().tobytes()
        return (image.width(), image.height(), len(img_bytes), hash(img_bytes[:1000]))

    @staticmethod
    def _content_key(item):
        """Stable key used for O(1) duplicate lookups."""
        if item["type"] == "text":
            return ("text", item["data"])
        if "path" in item:
            return ("image_path", item["path"])
        return ("image_key", item.get("key"))

    def _add_to_history(self, item, index=0):
        self.history.insert(index, item)
        self._content_index[self._content_key(item)] = item

    def _remove_from_history(self, item):
        """Remove one item from history + dedup index (list only, no widgets)."""
        try:
            self.history.remove(item)
        except ValueError:
            pass
        key = self._content_key(item)
        if self._content_index.get(key) is item:
            del self._content_index[key]

    @staticmethod
    def _serialize_item(item):
        """Turn a history entry into a JSON-safe dict for persisting pins."""
        if item["type"] == "text":
            payload = {"type": "text", "data": item["data"], "html": item.get("html", "")}
            if item.get("link_title"):
                payload["link_title"] = item["link_title"]
            if item.get("link_favicon_b64"):
                payload["link_favicon_b64"] = item["link_favicon_b64"]
            return payload

        image: QImage = item["data"]
        buffer = QBuffer()
        buffer.open(QIODevice.OpenModeFlag.WriteOnly)
        image.save(buffer, "PNG")
        image_b64 = base64.b64encode(bytes(buffer.data())).decode("ascii")
        buffer.close()
        return {"type": "image", "image_b64": image_b64, "path": item.get("path")}

    def _deserialize_item(self, raw):
        """Rebuild a history entry from a previously persisted dict, or None."""
        if raw.get("type") == "text":
            text = raw.get("data", "")
            item = {
                "type": "text",
                "data": text,
                "html": raw.get("html", ""),
                "pinned": True,
                "kind": classify_text(text),
            }
            if raw.get("link_title"):
                item["link_title"] = raw["link_title"]
                item["link_fetched"] = True
            if raw.get("link_favicon_b64"):
                item["link_favicon_b64"] = raw["link_favicon_b64"]
            return item

        if raw.get("type") == "image":
            try:
                png_bytes = base64.b64decode(raw.get("image_b64", ""))
            except (ValueError, TypeError):
                return None

            image = QImage()
            if not image.loadFromData(QByteArray(png_bytes), "PNG"):
                return None

            item = {"type": "image", "data": image, "pinned": True}
            saved_path = raw.get("path")
            if saved_path and os.path.isfile(saved_path):
                item["path"] = saved_path
            else:
                item["key"] = self._make_image_key(image)
            return item

        return None

    def _save_pinned(self):
        """Write every currently-pinned item to disk so a full quit doesn't lose them."""
        try:
            os.makedirs(APP_SUPPORT_DIR, exist_ok=True)
            payload = [self._serialize_item(it) for it in self.history if it.get("pinned")]
            tmp_path = PINNED_STORE_PATH + ".tmp"
            with open(tmp_path, "w", encoding="utf-8") as f:
                json.dump(payload, f)
            os.replace(tmp_path, PINNED_STORE_PATH)
        except OSError as e:
            print(f"[WARN] failed to save pinned items: {e}")

    def _load_pinned(self):
        """Load items pinned in a previous session, most-recently-pinned first."""
        if not os.path.isfile(PINNED_STORE_PATH):
            return

        try:
            with open(PINNED_STORE_PATH, "r", encoding="utf-8") as f:
                payload = json.load(f)
        except (OSError, json.JSONDecodeError) as e:
            print(f"[WARN] failed to load pinned items: {e}")
            return

        restored = [item for item in (self._deserialize_item(raw) for raw in payload) if item]
        self.history = restored + self.history
        for item in restored:
            self._content_index[self._content_key(item)] = item

    def _enforce_history_limit(self):
        """Trim oldest UNPINNED entries once history exceeds MAX_HISTORY."""
        while len(self.history) > self.MAX_HISTORY:
            idx = next(
                (i for i in range(len(self.history) - 1, -1, -1) if not self.history[i].get("pinned")),
                None,
            )
            if idx is None:
                break  # everything left is pinned; stop trimming
            self._remove_from_history(self.history[idx])

    # --- Link preview fetching (opt-in, off by default) ---------------------

    def _maybe_fetch_link_preview(self, item):
        if not self.fetch_previews_enabled or item.get("link_fetched"):
            return
        item["link_fetched"] = True

        raw = item["data"].strip()
        url = QUrl(raw if "://" in raw else "http://" + raw)
        if not url.host():
            return

        favicon_url = QUrl(f"https://www.google.com/s2/favicons?sz=64&domain={url.host()}")
        self._start_preview_request(favicon_url, item, "favicon")
        self._start_preview_request(url, item, "title")

    def _start_preview_request(self, url, item, kind):
        reply = self.network_manager.get(QNetworkRequest(url))
        reply.finished.connect(lambda: self._on_preview_reply(reply, item, kind))

    def _on_preview_reply(self, reply, item, kind):
        try:
            if reply.error() == reply.NetworkError.NoError:
                data = bytes(reply.readAll())
                if kind == "favicon" and data:
                    item["link_favicon_b64"] = base64.b64encode(data).decode("ascii")
                elif kind == "title":
                    match = TITLE_TAG_RE.search(data)
                    if match:
                        title = re.sub(r"\s+", " ", match.group(1).decode("utf-8", "ignore")).strip()
                        if title:
                            item["link_title"] = html.unescape(title)[:200]
                if item.get("pinned"):
                    self._save_pinned()
                self._refresh_row(item)
        finally:
            reply.deleteLater()

    def _refresh_row(self, item):
        row = self._row_widgets.get(id(item))
        if row is not None:
            row._build_content(item)

    # --- Clipboard polling / recording --------------------------------------

    def check_clipboard(self):
        """Poll the clipboard to detect new text, rich text (HTML), or images."""
        mime_data = self.clipboard.mimeData()
        if mime_data is None:
            return

        # Respect apps (e.g. password managers) that mark a copy as private.
        if any(mime_data.hasFormat(t) for t in PRIVATE_MARKER_TYPES):
            return

        # 1. Handle copied image files from Desktop or Finder
        if mime_data.hasUrls():
            urls = mime_data.urls()
            if urls and urls[0].isLocalFile():
                file_path = urls[0].toLocalFile()
                if file_path.lower().endswith(('.png', '.jpg', '.jpeg', '.webp', '.bmp', '.gif')):
                    if file_path != self.last_image_key:
                        image = QImage(file_path)
                        if not image.isNull():
                            self.last_image_key = file_path
                            self.last_clip_text = ""

                            key = ("image_path", file_path)
                            existing = self._content_index.get(key)
                            was_pinned = bool(existing and existing.get("pinned"))
                            if existing is not None:
                                self._remove_from_history(existing)

                            new_item = {"type": "image", "data": image, "path": file_path, "pinned": was_pinned}
                            self._add_to_history(new_item)
                            self._enforce_history_limit()
                            if was_pinned:
                                self._save_pinned()

                            self._render_list()
                    return

        # 2. Handle screenshots from memory
        if mime_data.hasImage():
            image: QImage = self.clipboard.image()
            if not image.isNull():
                img_key = self._make_image_key(image)

                if img_key != self.last_image_key:
                    self.last_image_key = img_key
                    self.last_clip_text = ""

                    key = ("image_key", img_key)
                    existing = self._content_index.get(key)
                    was_pinned = bool(existing and existing.get("pinned"))
                    if existing is not None:
                        self._remove_from_history(existing)

                    new_item = {"type": "image", "data": image, "key": img_key, "pinned": was_pinned}
                    self._add_to_history(new_item)
                    self._enforce_history_limit()
                    if was_pinned:
                        self._save_pinned()

                    self._render_list()

        # 3. Handle text with formatting (HTML + plain text fallback)
        elif mime_data.hasText():
            text = self.clipboard.text().strip()
            if not text:
                return

            html_text = mime_data.html() if mime_data.hasHtml() else ""

            if text != self.last_clip_text:
                self.last_clip_text = text
                self.last_image_key = None

                key = ("text", text)
                existing = self._content_index.get(key)
                was_pinned = bool(existing and existing.get("pinned"))
                if existing is not None:
                    self._remove_from_history(existing)

                kind = classify_text(text)
                new_item = {
                    "type": "text",
                    "data": text,
                    "html": html_text,
                    "pinned": was_pinned,
                    "kind": kind,
                }
                self._add_to_history(new_item)
                self._enforce_history_limit()
                if was_pinned:
                    self._save_pinned()
                if kind == "url":
                    self._maybe_fetch_link_preview(new_item)

                self._render_list()

    # --- List rendering ------------------------------------------------------

    def _sorted_history(self):
        """Pinned items first (in their existing relative order), then the rest."""
        return sorted(self.history, key=lambda it: 0 if it.get("pinned") else 1)

    def _add_item_to_widget(self, item):
        """Helper to create and insert a row (preview + pin/delete) into the list."""
        row = HistoryRowWidget(item)
        row.activated.connect(lambda it=item: self.paste_selected(it))
        row.pin_toggled.connect(lambda it=item: self.toggle_pin(it))
        row.delete_requested.connect(lambda it=item: self.delete_item(it))

        list_item = QListWidgetItem()
        list_item.setSizeHint(row.sizeHint())
        self.list_widget.addItem(list_item)
        self.list_widget.setItemWidget(list_item, row)

        self._row_widgets[id(item)] = row

    def _render_list(self):
        """Rebuild the visible list from history, applying the type filter and
        a simple "all words, any order" substring search."""
        query_words = self.search_bar.text().lower().split() if self.search_bar else []

        self.list_widget.clear()
        self._row_widgets.clear()

        for item in self._sorted_history():
            if self.active_filter == "text" and item["type"] != "text":
                continue
            if self.active_filter == "image" and item["type"] != "image":
                continue

            if query_words:
                if item["type"] != "text":
                    continue
                haystack = item["data"].lower()
                if not all(word in haystack for word in query_words):
                    continue

            self._add_item_to_widget(item)

    def set_filter(self, kind):
        self.active_filter = kind
        self._render_list()

    def toggle_pin(self, item):
        """Flip an entry's pinned state; pins are written to / removed from
        disk immediately, since only pinned items persist between launches."""
        item["pinned"] = not item.get("pinned", False)
        self._save_pinned()
        self._render_list()

    def delete_item(self, item):
        """Remove a single history entry (works for pinned entries too)."""
        was_pinned = item.get("pinned", False)
        self._remove_from_history(item)
        if was_pinned:
            self._save_pinned()
        self._render_list()

    def clear_history(self):
        """Wipe saved (unpinned) history and clear current clipboard.

        Pinned entries are intentionally kept - "Clear" is meant to sweep away
        clutter, not undo something the user deliberately pinned.
        """
        for item in [it for it in self.history if not it.get("pinned")]:
            self._remove_from_history(item)
        self.last_clip_text = ""
        self.last_image_key = None
        self.clipboard.clear()
        self._render_list()

    def paste_selected(self, item):
        """Copy the given history item back to the system clipboard, then
        optionally auto-paste it into whatever app had focus before Clippy."""
        if not item:
            return

        if item["type"] == "text":
            text = item["data"]
            html_text = item.get("html", "")
            self.last_clip_text = text
            self.last_image_key = None

            mime = QMimeData()
            mime.setText(text)
            if html_text:
                mime.setHtml(html_text)
            self.clipboard.setMimeData(mime)

        elif item["type"] == "image":
            image: QImage = item["data"]
            if "path" in item:
                self.last_image_key = item["path"]
                new_mime = QMimeData()
                new_mime.setUrls([QUrl.fromLocalFile(item["path"])])
                new_mime.setImageData(image)
                self.clipboard.setMimeData(new_mime)
            else:
                self.last_image_key = item.get("key")
                self.clipboard.setImage(image)
            self.last_clip_text = ""

        self.show_toast("copied!")

        if self.auto_paste_enabled and Quartz is not None and sys.platform == "darwin":
            self.hide()  # return focus to whatever app was active before Clippy
            QTimer.singleShot(80, simulate_cmd_v)

    def toggle_window(self):
        """Toggle window visibility strictly on shortcut call."""
        if self.isVisible():
            self.hide()
        else:
            self.search_bar.clear()
            self._render_list()
            self.show()
            self.raise_()
            self.activateWindow()
            self.search_bar.setFocus()

    def keyPressEvent(self, event):
        """Hide window on Escape key press."""
        if event.key() == Qt.Key.Key_Escape:
            self.hide()
        else:
            super().keyPressEvent(event)

    def shutdown(self):
        """Flush pinned items and stop the hotkey listener; safe to call twice."""
        self._save_pinned()
        if self.listener_thread:
            self.listener_thread.stop()

    def closeEvent(self, event):
        self.shutdown()
        event.accept()


