class HistoryRowWidget(QWidget):
    """Row rendered inside the list: type-aware preview + pin/delete toggles.

    Clicking anywhere on the row except the two buttons pastes the item;
    the pin/delete buttons only fire their own signals.
    """

    MONOSPACE = "'SF Mono', Menlo, Consolas, monospace"
    ELIDE_WIDTH = 170

    activated = Signal()
    pin_toggled = Signal()
    delete_requested = Signal()

    def __init__(self, item, parent=None):
        super().__init__(parent)

        layout = QHBoxLayout(self)
        layout.setContentsMargins(4, 2, 4, 2)
        layout.setSpacing(6)

        self.icon_label = QLabel(self)
        self.icon_label.setFixedSize(28, 28)
        self.icon_label.setScaledContents(True)
        self.icon_label.setAlignment(Qt.AlignmentFlag.AlignCenter)

        self.text_label = QLabel(self)
        self.text_label.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Preferred)

        self._build_content(item)

        self.pin_btn = PinButton(self)
        self.pin_btn.setChecked(bool(item.get("pinned", False)))
        self.pin_btn.clicked.connect(self.pin_toggled.emit)

        self.delete_btn = DeleteButton(self)
        self.delete_btn.clicked.connect(self.delete_requested.emit)

        layout.addWidget(self.icon_label)
        layout.addWidget(self.text_label, 1)
        layout.addWidget(self.pin_btn)
        layout.addWidget(self.delete_btn)

    def _elide(self, text):
        fm = self.text_label.fontMetrics()
        return fm.elidedText(text, Qt.TextElideMode.ElideRight, self.ELIDE_WIDTH)

    def _build_content(self, item):
        """(Re)renders icon + text for the given item; safe to call again later
        once async data (e.g. a fetched favicon/title) becomes available."""
        if item["type"] == "image":
            image: QImage = item["data"]
            pixmap = QPixmap.fromImage(image).scaled(
                28, 28, Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation,
            )
            self.icon_label.show()
            self.icon_label.setText("")
            self.icon_label.setPixmap(pixmap)
            self.icon_label.setStyleSheet("background: transparent; border-radius: 4px;")
            self.text_label.setStyleSheet("color: #cccccc; font-size: 13px; background: transparent;")
            self.text_label.setText(self._elide(" [Image / Screenshot]"))
            return

        raw_text = " ".join(item["data"].split())
        kind = item.get("kind", "text")

        if kind == "color":
            color = QColor(raw_text.strip())
            if not color.isValid():
                color = QColor("#666666")
            self.icon_label.show()
            self.icon_label.setText("")
            self.icon_label.setPixmap(QPixmap())
            self.icon_label.setStyleSheet(
                f"background-color: {color.name()}; border-radius: 6px; border: 1px solid #444444;"
            )
            self.text_label.setStyleSheet(
                f"color: {color.name()}; font-size: 13px; font-family: {self.MONOSPACE}; background: transparent;"
            )
            self.text_label.setText(self._elide(raw_text))

        elif kind == "url":
            self.icon_label.show()
            favicon_b64 = item.get("link_favicon_b64")
            if favicon_b64:
                pixmap = QPixmap()
                pixmap.loadFromData(base64.b64decode(favicon_b64))
                self.icon_label.setText("")
                self.icon_label.setPixmap(
                    pixmap.scaled(20, 20, Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation)
                )
                self.icon_label.setStyleSheet("background: transparent;")
            else:
                self.icon_label.setPixmap(QPixmap())
                self.icon_label.setText("\U0001F517")  # link emoji as a placeholder
                self.icon_label.setStyleSheet("background: transparent; font-size: 15px;")
            self.text_label.setStyleSheet("color: #6ab0f3; font-size: 13px; background: transparent;")
            self.text_label.setText(self._elide(item.get("link_title") or raw_text))

        elif kind == "code":
            self.icon_label.show()
            self.icon_label.setPixmap(QPixmap())
            self.icon_label.setText("</>")
            self.icon_label.setStyleSheet("background: transparent; color: #888888; font-size: 10px;")
            self.text_label.setStyleSheet(
                f"color: #cccccc; font-size: 12px; font-family: {self.MONOSPACE}; background: transparent;"
            )
            self.text_label.setText(self._elide(raw_text))

        else:
            self.icon_label.hide()
            self.text_label.setStyleSheet("color: #cccccc; font-size: 13px; background: transparent;")
            self.text_label.setText(self._elide(raw_text))

    def mousePressEvent(self, event):
        # Clicks that land on a button are consumed by the button itself and
        # never reach here, so any press we do see is a "paste" click.
        if event.button() == Qt.MouseButton.LeftButton:
            self.activated.emit()
        super().mousePressEvent(event)


class HotkeyCaptureField(QLineEdit):
    """Read-only field: click it, then press a modifier+key combo to record it.

    Supports letters/digits/symbols with at least one of Cmd/Ctrl/Alt/Shift
    held down. Function keys, arrows, etc. aren't mapped in this first pass.
    """

    def __init__(self, initial_hotkey, parent=None):
        super().__init__(parent)
        self.hotkey = initial_hotkey
        self.setReadOnly(True)
        self.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self.setPlaceholderText("Click, then press a combo…")
        self.setText(self._display(initial_hotkey))

    @staticmethod
    def _display(hotkey):
        return hotkey.replace("<", "").replace(">", "").replace("+", " + ").title()

    def keyPressEvent(self, event):
        key = event.key()
        if key in (Qt.Key.Key_Control, Qt.Key.Key_Shift, Qt.Key.Key_Alt, Qt.Key.Key_Meta):
            return  # wait for the actual (non-modifier) key

        mods = event.modifiers()
        parts = []
        if mods & Qt.KeyboardModifier.MetaModifier:
            parts.append("<cmd>")
        if mods & Qt.KeyboardModifier.ControlModifier:
            parts.append("<ctrl>")
        if mods & Qt.KeyboardModifier.AltModifier:
            parts.append("<alt>")
        if mods & Qt.KeyboardModifier.ShiftModifier:
            parts.append("<shift>")

        text = event.text()
        if not parts or not text or not text.isprintable():
            return  # require at least one modifier plus a real character

        parts.append(text.lower())
        self.hotkey = "+".join(parts)
        self.setText(self._display(self.hotkey))


