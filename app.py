class HotkeyListenerThread(QThread):
    """Background thread listening for the configured global shortcut."""

    def __init__(self, hk_signal, hotkey):
        super().__init__()
        self.signal = hk_signal
        self.hotkey = hotkey
        self.listener = None

    def run(self):
        try:
            hotkeys = {self.hotkey: self.on_triggered}
            with keyboard.GlobalHotKeys(hotkeys) as listener:
                self.listener = listener
                listener.join()
        except (KeyError, ValueError, RuntimeError) as e:
            print(f"[ERROR] pynput listener: {e}")

    def on_triggered(self):
        self.signal.triggered.emit()

    def stop(self):
        if self.listener:
            self.listener.stop()
        self.quit()
        self.wait()


class PinButton(QPushButton):
    """A small checkable button drawn as an outlined pin; fills white when pinned."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setCheckable(True)
        self.setFixedSize(22, 22)
        self.setCursor(Qt.CursorShape.PointingHandCursor)
        self.setStyleSheet("QPushButton { background: transparent; border: none; }")
        self.setToolTip("Pin")

    def enterEvent(self, event):
        self.update()
        super().enterEvent(event)

    def leaveEvent(self, event):
        self.update()
        super().leaveEvent(event)

    @staticmethod
    def _pin_path(rect: QRectF) -> QPainterPath:
        """Builds a simple thumbtack-style pin silhouette inside `rect`."""
        w, h = rect.width(), rect.height()
        x, y = rect.left(), rect.top()

        head_d = w * 0.62
        head_rect = QRectF(x + (w - head_d) / 2, y, head_d, head_d)

        path = QPainterPath()
        path.addEllipse(head_rect)

        needle = QPainterPath()
        needle.moveTo(x + w * 0.38, y + head_d * 0.85)
        needle.lineTo(x + w * 0.62, y + head_d * 0.85)
        needle.lineTo(x + w * 0.5, y + h)
        needle.closeSubpath()

        path.addPath(needle)
        return path

    def paintEvent(self, event):
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)

        rect = QRectF(self.rect().adjusted(3, 2, -3, -2))
        path = self._pin_path(rect)

        if self.isChecked():
            painter.setBrush(QBrush(QColor("#ffffff")))
            painter.setPen(QPen(QColor("#ffffff"), 1))
        else:
            color = QColor("#ffffff") if self.underMouse() else QColor("#999999")
            painter.setBrush(Qt.BrushStyle.NoBrush)
            painter.setPen(QPen(color, 1.4))

        painter.drawPath(path)


